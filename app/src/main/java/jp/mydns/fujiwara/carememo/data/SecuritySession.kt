package jp.mydns.fujiwara.carememo.data

/**
 * セキュリティに関する揮発的なセッション状態を管理するクラス。
 * アプリケーションの生存期間中、単一のインスタンスが保持されます。
 *
 * 【役割】
 * DataStore 等で永続化する必要のない、メモリ上のみで管理すべきセキュリティ状態を保持します。
 * 主に、外部アプリ連携時の自動ロック一時バイパスなどに使用されます。
 */
class SecuritySession {
    /**
     * アプリロックを一時的に無効化するフラグ。
     * PDF出力時のシステム共有シート連携など、アプリを一時離脱して戻る際の誤ロック防止に使用します。
     * スレッド間での可視性を保証するため @Volatile を付与しています。
     */
    @Volatile
    var isLockBypassed: Boolean = false
}
