package jp.mydns.fujiwara.carememo.logic.common

/**
 * Enum：BirthEra
 *
 * 【役割】
 * 利用者の生年月日で使用する「元号」を定義します。
 *
 * 【設計指針：Pure Kotlin / Android 非依存】
 * 1. 和暦（昭和・平成・令和）および西暦の選択肢を提供します。
 * 2. 日本の介護現場での利用を想定し、主要な和暦をサポートします。
 * 3. 1900年〜1926年（明治・大正）の利用者は、システム仕様に基づき「西暦 (AD)」として扱い、
 *    将来的な保守コストの増大を抑制します。
 */
enum class BirthEra {
    /** 西暦（Anno Domini）: 主に明治・大正期、または和暦を希望しない場合に使用 */
    AD,
    /** 昭和（Showa）: 1926/12/25 〜 1989/01/07 */
    SHOWA,
    /** 平成（Heisei）: 1989/01/08 〜 2019/04/30 */
    HEISEI,
    /** 令和（Reiwa）: 2019/05/01 〜 */
    REIWA
}
